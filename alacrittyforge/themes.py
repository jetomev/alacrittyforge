"""Themes: colour files in ~/.config/alacritty/themes (v1.0.0).

Alacritty can be themed two ways, and alacrittyForge handles both:
- **a theme file**, named in ``general.import``; the settings file's own
  ``[colors]``, if any, win over it (the importing file is applied last);
- **colours in the settings file itself** (``[colors]``), shown as "My colours".

Using a theme puts it first in ``general.import`` (other imports stay) and
takes the settings file's own colours out, because they would hide it; the
review says so, and a backup is made. Files another tool maintains (hypeForge
writes "Do not edit; it is rewritten") are **locked**: listed and usable,
never written. New theme files (Adjust colours, Save my colours, Install) are
staged like any change and written by the save, never over an existing file.
"""

from __future__ import annotations

import re
import tomllib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import tomlkit

THEMES_DIR = Path.home() / ".config" / "alacritty" / "themes"
LOCK_MARKS = ("do not edit", "generated by")
COLOUR_RE = re.compile(r"#[0-9a-fA-F]{6}")

